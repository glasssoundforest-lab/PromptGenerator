// ============================================================
//  辞書テンプレート (Rust形式)
//
//  使い方
//   1. このファイルをコピーして、好きな名前 (例: dic_all.rs) にします。
//   2. 下の Category を編集・追加します。
//   3. アプリの「辞書の切り替え」でそのファイルを選びます。
//      (編集後は「再読み込み」で反映されます)
//
//  書き方
//   - Category { id: "ID", name: "表示名", kinds: &["種類A", "種類B"], entries: &[("English", "日本語", "種類A"), ...] },
//   - id はカテゴリごとに重複させず、空白を入れないでください。
//   - カテゴリの先頭で、名前 (name) と、中に入っている単語の種類 (kinds) を宣言します。
//   - entries は (英語プロンプト, 日本語, 種類) の組です。1つ以上必要です。
//     種類は kinds に書いた名前にします。語は種類ごとにまとめて並べてください。
//     辞書ピッカーでは種類ごとに区切って表示され、「すべて選ぶ」で種類ごとまとめて選べます。
//   - kinds と 3つ目の種類は省略できます (省略したカテゴリは区切りなしで表示されます)。
//     kinds を使うカテゴリで種類を書かなかった語は、最後の「その他」にまとまります。
//   - 英語はプロンプトに入る語、日本語は画面に表示される語です。
//   - Rustとしてコンパイルはされません。文字列の並びだけを読むので、
//     format! や定数で組み立てた語は使えません。
//   - 文字列の中で " を使うときは \" と書きます。
//
//  注意
//   - 選んだファイルの内容だけが辞書になります (他のファイルや初期辞書は併用されません)。
//   - 入力欄は、下の「使えるID」と同じ id のカテゴリに結びついています。
//     ここに無いIDのカテゴリは辞書ウィンドウで選べますが、入力欄には結びつきません。
//     ファイルに無いIDの入力欄は、辞書ボタンを押しても候補が出ません (自由入力は使えます)。
//   - 全部入りの辞書は Dict/dictionary.json です。これを元に編集するのも簡単です。
//
//  使えるID (入力欄に結びついているもの)
//   face_nose                      輪郭・鼻
//   mouth_all                      口・唇
//   eye_all                        目・瞳
//   brow_lash                      まつ毛・眉
//   skin_all                       肌
//   hair_cut                       髪型・長さ
//   hair_arrange                   前髪・結い髪・毛先
//   hair_color_quality             髪の色・髪質
//   wear_all                       メガネ・帽子・耳飾り
//   eye_adult                      瞳の状態(成人向け)
//   body_head                      身長・体型・首
//   torso                          胸・ウエスト・ヒップ
//   limbs                          手・腕・脚・足
//   body_adult                     身体・部位(成人向け)
//   outfit                         制服・ドレス・水着
//   tops_bottoms                   トップス・ボトムス
//   legwear_shoes                  靴下・靴
//   fashion_style                  ファッション系統
//   cloth_material                 素材・質感
//   accessories                    アクセサリー・バッグ・小物
//   cloth_adult                    衣装の状態・拘束(成人向け)
//   pose_main                      姿勢・動作
//   pose_hands                     腕・手の仕草
//   gaze                           視線・顔の向き
//   pose_adult                     ポーズ・行為(成人向け)
//   expr_all                       表情・感情
//   expr_adult                     表情・反応(成人向け)
//   scene_situation                シチュエーション
